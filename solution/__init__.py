"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

from .chunked_loss import patch_sft_compute_loss
from .embed_fp16 import patch_prepare_model_for_kbit_training
from .mlp_fp16 import patch_qwen2_mlp_fp16
from .nf4_dequant import patch_linear4bit_own_dequant
from .precompile import start_precompile
from .residual_fp16 import patch_embed_output_fp16
from .rmsnorm import patch_qwen2_rmsnorm
from .rope import patch_qwen2_rope
from .swiglu import patch_qwen2_mlp
from .unpad import patch_qwen2_unpad_mlp


def apply():
    patch_prepare_model_for_kbit_training()  # exp/0020 (M5): store frozen tied embedding in fp16
    patch_embed_output_fp16()  # exp/0021 (S1): fp16 residual stream entry cast
    patch_qwen2_mlp()  # the example: works out of the box, does not count as your own kernel
    patch_qwen2_mlp_fp16()  # exp/0007 (H5): wraps the patched MLP — one fp16 entry cast
    patch_linear4bit_own_dequant()  # exp/speed-0028 (P5): per-use NF4 dequant, own kernel, no fp16 weight cache
    patch_qwen2_unpad_mlp()  # exp/0009 (H7) + exp/0024 (P1): norm+MLP on real rows only
    patch_qwen2_rmsnorm()  # exp/0001: own fused RMSNorm (forward + backward)
    patch_qwen2_rope()  # exp/0025 (P9): own fused RoPE (forward + backward)
    patch_sft_compute_loss()  # exp/0003 + exp/0025 (P10): own chunked lm-head CE + active-row bwd
    start_precompile()  # exp/speed-0028 (P8): warm own kernels while the model builds
